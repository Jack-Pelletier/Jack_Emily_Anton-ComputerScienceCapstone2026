-- DROP DATABASE IF EXISTS CapstoneDB;
CREATE DATABASE IF NOT EXISTS CapstoneDB;

USE CapstoneDB;

CREATE TABLE IF NOT EXISTS FacultyAccount(
AccountID INT NOT NULL AUTO_INCREMENT,
Email VARCHAR (100),
NormalizedEmail VARCHAR(100) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin
  GENERATED ALWAYS AS (LOWER(TRIM(Email))) STORED,
PRIMARY KEY(AccountID),
UNIQUE KEY uq_faculty_normalized_email (NormalizedEmail)
);

CREATE TABLE IF NOT EXISTS Project(
ProjectID INT NOT NULL AUTO_INCREMENT,
ProjectName VARCHAR(500),
ProjectDescription VARCHAR(2000),
Industry VARCHAR(100),
Approved BOOLEAN NOT NULL DEFAULT FALSE,
PRIMARY KEY(ProjectID)
);

CREATE TABLE IF NOT EXISTS StudentInfo(
StudentID INT NOT NULL AUTO_INCREMENT,
ProjectID INT NOT NULL, 
FOREIGN KEY (ProjectID) REFERENCES Project(ProjectID),
StudentName VARCHAR(150),
StudentEmail VARCHAR(100),
StudentPhoneNumber VARCHAR (14),
StudentInfoPublic BOOLEAN,
PRIMARY KEY(StudentID)
);

CREATE TABLE IF NOT EXISTS StudentWebsites(
WebsiteID INT NOT NULL AUTO_INCREMENT, 
StudentID INT NOT NULL,
FOREIGN KEY (StudentID) REFERENCES StudentInfo(StudentID),
WebsiteName VARCHAR(100),
WebsiteURL VARCHAR(500),
PRIMARY KEY(WebsiteID)
);

CREATE TABLE IF NOT EXISTS Keywords(
KeywordID INT NOT NULL AUTO_INCREMENT, 
KeywordName VARCHAR(100) NOT NULL, 
PRIMARY KEY (KeywordID),
UNIQUE (KeywordName)
);

CREATE TABLE IF NOT EXISTS ProjectKeywords(
ProjectID INT NOT NULL, 
KeywordID INT NOT NULL, 
PRIMARY KEY (ProjectID, KeywordID), 
FOREIGN KEY (ProjectID) REFERENCES Project(ProjectID),
FOREIGN KEY (KeywordID) REFERENCES Keywords(KeywordID)
);

CREATE TABLE IF NOT EXISTS ProjectPDF(
PDFID INT NOT NULL AUTO_INCREMENT, 
ProjectID INT NOT NULL, 
PDFBucket VARCHAR(100) NOT NULL DEFAULT 'project-pdfs',
PDFPath VARCHAR(500) NOT NULL, 
PDFOriginalName VARCHAR(225) NOT NULL,
UploadedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

PRIMARY KEY (PDFID),
FOREIGN KEY (ProjectID) REFERENCES Project(ProjectID) ON DELETE CASCADE

);

CREATE TABLE IF NOT EXISTS PDFCleanup (
  CleanupID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  PDFBucket VARCHAR(100) NOT NULL,
  PDFPath VARCHAR(500) NOT NULL,
  CreatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY UniquePDFCleanup (PDFBucket, PDFPath)
);


